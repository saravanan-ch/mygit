#pop() method removes and returns an arbitrary (random) element from a set.
#Sets do not maintain indexing like lists, so any item can be removed randomly

numbers = {10, 20, 30}
value = numbers.pop()
print(value)
print(numbers)


fruits = {"apple", "banana", "orange"}
removed = fruits.pop()
