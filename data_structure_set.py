#union() method returns a new set containing all unique elements from two or more sets.
set1 = {1, 2}
set2 = {2, 3}
set3 = {3, 4}
result = set1.union(set2, set3)
print(result)

#print(set1 | set2) - This is same for above

set1 = {1, 2, 3}
set2 = {3, 4, 5}
result = set1.union(set2)
print(set1)
print(result) #Original sets are not modified

#intersection() method returns the common elements present in both sets.
set1 = {1, 2, 3, 4}
set2 = {2, 3, 5}
set3 = {2, 3, 6}
result = set1.intersection(set2, set3)
print(result)

set1 = {1, 2, 3}
set2 = {2, 3, 4}
print(set1 & set2) #This is same as above

set1 = {1, 2}
set2 = {3, 4}
print(set1.intersection(set2)) #An empty set means there are no common elements.

#intersection_update()
set1 = {1, 2, 3, 4}
set2 = {3, 4, 5, 6}
set1.intersection_update(set2)
print(set1) #Modifies the original set

