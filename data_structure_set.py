#add() method is used to add a single element to a set.
numbers = {10, 20, 30}
(numbers.add(500))
print(numbers)

#Tuples are immutable, so they can be added to a set.
data = {1, 2, 3}
data.add((4, 5))
print(data)

#Lists are mutable and therefore unhashable.
data = {1, 2, 3}
data.add([4, 5])
print(data)

