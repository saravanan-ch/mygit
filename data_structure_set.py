#symmetric_difference() method returns elements that are present in either set, but not in both.
set1 = {1, 2, 3, 4}
set2 = {3, 4, 5, 6}
result = set1.symmetric_difference(set2)
print(result)

set1 = {1, 2, 3}
set2 = {3, 4, 5}
print(set1 ^ set2)

#No common elements, Returns all.
set1 = {1, 2}
set2 = {3, 4}
print(set1.symmetric_difference(set2))

#Same elements, Returns nothing
set1 = {1, 2, 3}
set2 = {1, 2, 3}
print(set1.symmetric_difference(set2))

#issubset() method checks whether all elements of one set are present in another set.
